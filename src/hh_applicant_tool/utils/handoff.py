"""Горячие чаты (приглашение на живой разговор передано кандидату): когда напоминать и
шпаргалка к разговору. Чистые функции — покрыты tests/test_handoff.py."""
from __future__ import annotations

import html

# (через сколько часов без ответа кандидата, текст) — по возрастанию
STAGES: tuple[tuple[int, str], ...] = (
    (3, "ждут твоего ответа уже 3 ч"),
    (24, "сутки без твоего ответа"),
    (72, "3 дня без ответа — последнее напоминание"),
)


def due_stage(hours_waiting: float, sent: set[int]) -> tuple[int, str] | None:
    """Какое напоминание слать сейчас: самое позднее наступившее и ещё не отправленное.
    Пропущенные ранние стадии не догоняем (после простоя — сразу актуальная)."""
    for hours, label in reversed(STAGES):
        if hours_waiting >= hours:
            return None if hours in sent else (hours, label)
    return None


