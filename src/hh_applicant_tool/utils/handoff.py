def prep_card(vacancy: str, employer: str, invite_text: str, prep: str, link: str) -> str:
    """HTML-сообщение в Telegram: приглашение + шпаргалка."""
    return (
        f"🔔 <b>Приглашение</b> — {html.escape(vacancy or '')}"
        + (f" ({html.escape(employer)})" if employer else "")
        + f"\n«{html.escape(' '.join((invite_text or '').split())[:400])}»"
        + (f"\n\n<b>Шпаргалка к разговору</b>\n{html.escape(prep.strip()[:1500])}" if prep else "")
        + (f'\n\n<a href="{html.escape(link)}">ответить в чате →</a>' if link else "")
    )
